/**
 * The save-history report (ADR 0112): what each part of the story reads from
 * the others, and how saves from each release answer for what was added under
 * them. Writers read it before drafting a scene that depends on the past.
 *
 *   npm run docs:saves            writes docs/save-history.md
 *   npm run docs:saves -- --check fails when the committed file is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { CONTENT } from '../../src/content';
import { REGIONS } from '../../src/content/regions';
import { REGION_CONTENT } from '../../src/content/regions/content';
import { FLAG_BACKFILLS, HISTORY_REV } from '../../src/content/story/flagBackfills';
import { FLAG_REGISTRY, LATE_SCENES } from '../../src/content/story/flags';
import type { OldSavesAnswer } from '../../src/content/story/flags';
import { registryEntryFor } from '../../src/content/story/flagUsage';
import { lateScenes, lateWrites, readersOf } from '../../src/content/story/saveHistory';
import type { HistoryInput } from '../../src/content/story/saveHistory';
import { historyInput, USES_NOW } from '../../src/content/story/saveHistoryNow';
import { describe } from '../../src/core/story/conditions';
import { loadReleases } from '../saves/releases';

const GENERATED = '<!-- Generated by scripts/docs/save-history.ts. Do not edit by hand. -->';
const SHARED = 'Shared (disciplines, followers, the journal, the app)';

interface Part {
  readonly region: string;
  readonly name: string;
}

/** Area to the part of the story it belongs to: a story file, or its region's maps and people. */
function partsByArea(): Map<string, Part> {
  const parts = new Map<string, Part>();
  for (const region of REGION_CONTENT) {
    const name = REGIONS.find((manifest) => manifest.id === region.id)?.name ?? region.id;
    const place: Part = { region: name, name: `${name}: maps, people and fights` };
    for (const map of region.maps) parts.set(`map:${map.id}`, place);
    for (const encounter of region.encounters) parts.set(`encounter:${encounter.id}`, place);
    for (const resident of region.residents) parts.set(`resident:${resident.id}`, place);
    for (const group of region.storyGroups)
      for (const node of group.nodes)
        parts.set(`story:${node.id}`, { region: name, name: `${name}: ${group.title}` });
  }
  return parts;
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function areas(list: readonly string[], most = 6): string {
  const shown = list.slice(0, most).map((area) => `\`${area}\``);
  return list.length > most
    ? `${shown.join(', ')} and ${list.length - most} more`
    : shown.join(', ');
}

function answerText(answer: OldSavesAnswer | undefined): string {
  if (!answer) return 'none declared';
  const word =
    answer.answer === 'backfill'
      ? 'Backfill rule'
      : answer.answer === 'open'
        ? 'Still open'
        : 'Stays unset';
  return `**${word}.** ${answer.why}`;
}

export function saveHistoryReport(input: HistoryInput): string {
  const parts = partsByArea();
  const partOf = (area: string): Part => parts.get(area) ?? { region: SHARED, name: SHARED };
  const readers = readersOf(USES_NOW);
  const lines: string[] = [
    '# What the story remembers, and what old saves answer',
    '',
    GENERATED,
    '',
    'Read this before drafting a scene that depends on something that happened earlier. It is generated from the content, the flag registry (`src/content/story/flags.ts`) and the release fixtures (`src/core/save/fixtures/releases/`); ADR 0112 has the rules. Regenerate with `npm run docs:saves`.',
    '',
    `Content is at history revision **${HISTORY_REV}**. Releases frozen so far: ${input.releases.map((release) => `\`${release.release}\` (${release.frozen})`).join(', ') || 'none'}.`,
    '',
    '## Before you read the past',
    '',
    '- A flag set and read inside one new region needs nothing: no save has been there.',
    '- A flag that something reads and that gains a write in a region **already released** needs an answer for the saves of that release, in its registry entry (`oldSaves`). So does a new scene there that a `visited` condition reads (`LATE_SCENES`).',
    '- The answers: a **backfill rule** (the old save shows what happened: give it the flag on load), **still open** (every save can still play the scene), or **stays unset** (a save past it answers "never happened", and the readers have a line for that).',
    '- `npm test` (`saveHistory.test.ts`) fails with the flag, its readers and the release until the answer is declared, and plays every frozen save forward to the ending to compare it with a new game.',
    '',
    '## What each part of the story reads from the others',
    '',
    'Flags read in one part and written in another. A reader in a later region depends on every save having passed the writer with the flag in hand.',
    '',
  ];

  // part -> key -> { writers (outside the part), readers (inside the part) }
  const crossing = new Map<string, Map<string, { from: Set<string>; here: Set<string> }>>();
  for (const [key, readAreas] of readers) {
    const writers = input.now.writes.filter((site) => site.key === key);
    for (const area of readAreas) {
      const part = partOf(area);
      const outside = writers.filter((site) => partOf(site.area).name !== part.name);
      if (outside.length === 0) continue;
      const forPart =
        crossing.get(part.name) ?? new Map<string, { from: Set<string>; here: Set<string> }>();
      const entry = forPart.get(key) ?? { from: new Set<string>(), here: new Set<string>() };
      for (const site of outside) entry.from.add(partOf(site.area).name);
      entry.here.add(area);
      forPart.set(key, entry);
      crossing.set(part.name, forPart);
    }
  }
  const order = [...new Set([...parts.values()].map((part) => part.name)), SHARED];
  for (const name of order) {
    const forPart = crossing.get(name);
    if (!forPart) continue;
    lines.push(
      `### ${name}`,
      '',
      '| Flag | Means | Written in | Read here by |',
      '| --- | --- | --- | --- |',
    );
    for (const key of [...forPart.keys()].sort()) {
      const entry = forPart.get(key);
      if (!entry) continue;
      const meaning = registryEntryFor(FLAG_REGISTRY, key)?.meaning ?? '';
      lines.push(
        `| \`${key}\` | ${cell(meaning)} | ${cell([...entry.from].sort().join('; '))} | ${areas([...entry.here].sort())} |`,
      );
    }
    lines.push('');
  }

  lines.push(
    '## Remembered, and read by nothing yet',
    '',
    'Flags the game sets that no scene reads. A later region may read them, and a save holds them only if it passed the writer after the write existed.',
    '',
    '| Flag | Means | Written at |',
    '| --- | --- | --- |',
  );
  const unread = new Map<string, string[]>();
  for (const site of input.now.writes) {
    const read = [...readers.keys()].some((key) => key === site.key);
    if (read || site.key.endsWith('.*') || site.key.startsWith('guidance.')) continue;
    unread.set(site.key, [...(unread.get(site.key) ?? []), site.area]);
  }
  for (const key of [...unread.keys()].sort())
    lines.push(
      `| \`${key}\` | ${cell(registryEntryFor(FLAG_REGISTRY, key)?.meaning ?? '')} | ${areas(unread.get(key) ?? [])} |`,
    );
  lines.push('');

  lines.push(
    '## Added under a release, and how its saves answer',
    '',
    "Every flag write and every `visited`-read scene that today's story has and a release shipped without, inside a region that release contained.",
    '',
  );
  for (const release of input.releases) {
    lines.push(
      `### Release \`${release.release}\``,
      '',
      `Frozen ${release.frozen} from commit \`${release.commit}\`, history revision ${release.historyRev}. ${release.note}`,
      '',
    );
    const writes = lateWrites(input).filter((late) => late.release === release.release);
    const scenes = lateScenes(input).filter((late) => late.release === release.release);
    if (writes.length + scenes.length === 0) {
      lines.push('Nothing has been added under this release.', '');
      continue;
    }
    lines.push('| Added | Where | Read by | Saves of this release |', '| --- | --- | --- | --- |');
    const byKey = new Map<string, typeof writes>();
    for (const late of writes)
      byKey.set(late.site.key, [...(byKey.get(late.site.key) ?? []), late]);
    for (const key of [...byKey.keys()].sort()) {
      const sites = byKey.get(key) ?? [];
      lines.push(
        `| flag \`${key}\` | ${areas(sites.map((late) => late.site.area))} | ${areas(sites[0]?.readers ?? [], 4)} | ${cell(answerText(registryEntryFor(FLAG_REGISTRY, key)?.oldSaves))} |`,
      );
    }
    for (const late of [...scenes].sort((a, b) => a.node.localeCompare(b.node)))
      lines.push(
        `| scene \`${late.node}\` | \`story:${late.node}\` | ${areas(late.readers, 4)} | ${cell(answerText(Object.hasOwn(LATE_SCENES, late.node) ? LATE_SCENES[late.node] : undefined))} |`,
      );
    lines.push('');
  }

  lines.push('## Backfill rules', '');
  if (FLAG_BACKFILLS.length === 0) lines.push('None yet.', '');
  else {
    lines.push('| Rev | Gives | To a save where |', '| --- | --- | --- |');
    for (const rule of FLAG_BACKFILLS) {
      const gives =
        'node' in rule
          ? `scene \`${rule.node}\` counted as visited`
          : 'adjust' in rule
            ? `\`${rule.key}\` moved by ${rule.adjust > 0 ? '+' : ''}${rule.adjust}`
            : `\`${rule.key}\` = ${JSON.stringify(rule.set)}`;
      lines.push(`| ${rule.rev} | ${gives} | ${cell(describe(CONTENT, rule.when))} |`);
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

export async function runCli(
  args: readonly string[] = process.argv.slice(2),
  output = resolve('docs/save-history.md'),
): Promise<number> {
  if (args.some((argument) => argument !== '--check')) {
    console.error('Usage: npm run docs:saves -- [--check]');
    return 1;
  }
  const input = historyInput(loadReleases().map((release) => release.snapshot));
  const options = (await resolveConfig(output)) ?? {};
  const generated = await format(saveHistoryReport(input), { ...options, filepath: output });
  if (args.includes('--check')) {
    const current = await readFile(output, 'utf8').catch(() => '');
    if (current !== generated) {
      console.error(
        'docs/save-history.md is missing or stale. Run `npm run docs:saves` and commit it.',
      );
      return 1;
    }
    return 0;
  }
  await writeFile(output, generated, 'utf8');
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  runCli()
    .then((code) => {
      process.exitCode = code;
    })
    .catch((error: unknown) => {
      console.error(error);
      process.exitCode = 1;
    });
}
