import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { ALL_STORY, CONTENT, STORY_ENTRY } from '../../src/content';
import { REGION_CONTENT } from '../../src/content/regions/content';
import type { StoryGroup } from '../../src/content/regions';
import { describe } from '../../src/core/story/conditions';
import type { ContentIndex, FlagValue, StoryNode } from '../../src/core/types';

export type { StoryGroup };

/** Every region's story files (ADR 0111); coverage validation rejects unregistered runtime nodes. */
export const STORY_GROUPS: readonly StoryGroup[] = REGION_CONTENT.flatMap(
  (region) => region.storyGroups,
);

export interface StoryGraphOptions {
  readonly content?: ContentIndex;
  readonly groups?: readonly StoryGroup[];
  /** The array is checked as well as the index, which cannot retain duplicate IDs. */
  readonly runtimeNodes?: readonly StoryNode[];
  readonly entryNodeIds?: readonly string[];
}

export interface StoryEdge {
  readonly from: string;
  readonly to: string;
  readonly label: string;
}

export interface GraphNode {
  readonly node: StoryNode;
  readonly group: string;
  readonly entry: boolean;
}

export interface StoryPart {
  readonly group: string;
  readonly number: number;
  readonly entry: string;
  readonly nodeIds: readonly string[];
}

export interface StoryGraph {
  readonly content: ContentIndex;
  readonly groups: readonly StoryGroup[];
  readonly nodes: readonly GraphNode[];
  readonly edges: readonly StoryEdge[];
  readonly parts: readonly StoryPart[];
}

const MAX_NODES = 80;
const GENERATED = '<!-- Generated by scripts/docs/story-graph.ts. Do not edit by hand. -->';

function compare(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function assignments(values: Readonly<Record<string, FlagValue>>): string {
  return Object.keys(values)
    .sort(compare)
    .map((key) => `${key}=${JSON.stringify(values[key])}`)
    .join(', ');
}

function transitions(node: StoryNode, content: ContentIndex): StoryEdge[] {
  const edge = (to: string, label: string): StoryEdge => ({ from: node.id, to, label });
  switch (node.kind) {
    case 'choice':
      return node.options.map((option) => {
        const text = [short(option.label)];
        if (option.requires) text.push(`requires: ${describe(content, option.requires)}`);
        if (option.setFlags && Object.keys(option.setFlags).length)
          text.push(`set: ${assignments(option.setFlags)}`);
        if (option.adjust) text.push(`standing deltas: ${assignments(option.adjust)}`);
        return edge(option.next, text.join('; '));
      });
    case 'branch':
      return [
        edge(
          node.ifSet,
          `${node.flag}: truthy (${describe(content, { kind: 'flag', key: node.flag, op: 'set' })})`,
        ),
        edge(
          node.ifUnset,
          `${node.flag}: falsy (${describe(content, { kind: 'flag', key: node.flag, op: 'unset' })})`,
        ),
      ];
    case 'battle':
      return [edge(node.next, 'Victory'), edge(node.onDefeat, 'Defeat')];
    case 'flags': {
      const text = [`set: ${assignments(node.set) || '(none)'}`];
      if (node.phase) text.push(`phase: ${node.phase}`);
      if (node.grantXp !== undefined) text.push(`grant XP: ${node.grantXp}`);
      if (node.residentProfiles)
        text.push(`resident profiles: ${assignments(node.residentProfiles)}`);
      return [edge(node.next, text.join('; '))];
    }
    case 'dialogue':
      return [edge(node.next, 'Next')];
    case 'explore':
      return [
        edge(
          node.next,
          content.maps.get(node.mapId)?.exits?.length
            ? 'Legacy/audit exit (live map exits differ)'
            : 'Next',
        ),
      ];
    case 'end':
      return node.next === undefined ? [] : [edge(node.next, 'Continue after ending')];
  }
}

/** Own every node exactly once, starting with entry points and then cycle/disconnected roots. */
function splitGroup(
  group: StoryGroup,
  nodes: readonly GraphNode[],
  edges: readonly StoryEdge[],
): StoryPart[] {
  const ids = nodes.filter((item) => item.group === group.slug).map((item) => item.node.id);
  if (ids.length === 0) return [];
  const entries = nodes
    .filter((item) => item.group === group.slug && item.entry)
    .map((item) => item.node.id);
  if (ids.length <= MAX_NODES)
    return [{ group: group.slug, number: 1, entry: entries[0] ?? ids[0] ?? '', nodeIds: ids }];

  const remaining = new Set(ids);
  const entrySet = new Set(entries);
  const outgoing = new Map<string, string[]>();
  for (const edge of edges) {
    const targets = outgoing.get(edge.from) ?? [];
    targets.push(edge.to);
    outgoing.set(edge.from, targets);
  }
  const parts: StoryPart[] = [];
  for (const seed of [...entries, ...ids]) {
    if (!remaining.has(seed)) continue;
    const queue = [seed];
    while (queue.length) {
      const entry = queue[0];
      if (entry === undefined) break;
      const owned: string[] = [];
      while (queue.length && owned.length < MAX_NODES) {
        const id = queue.shift();
        if (id === undefined || !remaining.delete(id)) continue;
        owned.push(id);
        for (const target of outgoing.get(id) ?? []) {
          if (remaining.has(target) && !entrySet.has(target) && !queue.includes(target))
            queue.push(target);
        }
      }
      if (owned.length)
        parts.push({ group: group.slug, number: parts.length + 1, entry, nodeIds: owned });
    }
  }
  return parts;
}

export function buildStoryGraph(options: StoryGraphOptions = {}): StoryGraph {
  const content = options.content ?? CONTENT;
  const groups = [...(options.groups ?? STORY_GROUPS)].sort((a, b) => compare(a.slug, b.slug));
  const runtimeNodes =
    options.runtimeNodes ?? (content === CONTENT ? ALL_STORY : [...content.story.values()]);
  const runtimeIds = new Set<string>();
  for (const node of runtimeNodes) {
    if (runtimeIds.has(node.id)) throw new Error(`Duplicate runtime story ID: ${node.id}`);
    runtimeIds.add(node.id);
    if (!content.story.has(node.id))
      throw new Error(`Runtime story ID missing from index: ${node.id}`);
  }
  for (const [id, node] of content.story) {
    if (id !== node.id) throw new Error(`Story index key ${id} does not match node ID ${node.id}`);
    if (!runtimeIds.has(id)) throw new Error(`Story index ID omitted from runtime nodes: ${id}`);
  }

  const owners = new Map<string, string>();
  const slugs = new Set<string>();
  for (const group of groups) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(group.slug) || slugs.has(group.slug))
      throw new Error(`Invalid or duplicate story group slug: ${group.slug}`);
    slugs.add(group.slug);
    for (const node of group.nodes) {
      if (!runtimeIds.has(node.id))
        throw new Error(`Unknown story ID in group ${group.slug}: ${node.id}`);
      if (owners.has(node.id)) throw new Error(`Duplicate grouped story ID: ${node.id}`);
      owners.set(node.id, group.slug);
    }
  }
  for (const id of runtimeIds) {
    if (!owners.has(id)) throw new Error(`Runtime story ID has no registered group: ${id}`);
  }
  const sortedNodes = [...content.story.values()].sort((a, b) => compare(a.id, b.id));
  const edges = sortedNodes.flatMap((node) => transitions(node, content));
  const entries = new Set(options.entryNodeIds ?? (content === CONTENT ? [STORY_ENTRY] : []));
  const internallyReached = new Set<string>();
  for (const edge of edges) {
    if (!content.story.has(edge.to))
      throw new Error(`Missing story target: ${edge.from} -> ${edge.to}`);
    if (owners.get(edge.from) !== owners.get(edge.to)) entries.add(edge.to);
    else internallyReached.add(edge.to);
  }
  // These are entry annotations only. Map travel is not a story-node transition.
  for (const map of content.maps.values()) {
    for (const npc of map.npcs) {
      entries.add(npc.node);
      for (const route of npc.routes ?? []) entries.add(route.node);
    }
    for (const trigger of map.triggers ?? []) entries.add(trigger.node);
  }
  for (const id of entries) {
    if (!content.story.has(id)) throw new Error(`Missing story entry target: ${id}`);
  }
  const nodes: GraphNode[] = sortedNodes.map((node) => {
    if (node.kind === 'battle' && !content.encounters.has(node.encounterId))
      throw new Error(`Missing encounter ${node.encounterId} at story node ${node.id}`);
    const group = owners.get(node.id);
    if (group === undefined) throw new Error(`Missing group for ${node.id}`);
    return { node, group, entry: entries.has(node.id) || !internallyReached.has(node.id) };
  });
  return {
    content,
    groups,
    nodes,
    edges,
    parts: groups.flatMap((group) => splitGroup(group, nodes, edges)),
  };
}

function short(text: string): string {
  const characters = Array.from(text.replace(/\s+/g, ' ').trim());
  return characters.length > 64 ? `${characters.slice(0, 63).join('')}…` : characters.join('');
}

/** Quoted Mermaid labels still need entities for syntax, HTML and Markdown delimiters. */
export function escapeMermaidLabel(text: string): string {
  return text.replace(/[#&"<>|`\\\r\n]/g, (character) => {
    const entities: Record<string, string> = {
      '#': '#35;',
      '&': '#amp;',
      '"': '#quot;',
      '<': '#lt;',
      '>': '#gt;',
      '|': '#124;',
      '`': '#96;',
      '\\': '#92;',
      '\r': ' ',
      '\n': ' ',
    };
    return entities[character] ?? character;
  });
}

function title(node: StoryNode, content: ContentIndex): string {
  switch (node.kind) {
    case 'dialogue':
      return short(`${node.speaker}: ${node.lines[0] ?? ''}`);
    case 'choice':
      return short(`${node.speaker}: ${node.prompt}`);
    case 'explore':
      return short(`Explore ${node.mapId}: ${node.objective}`);
    case 'branch':
      return short(`Branch: ${node.flag}`);
    case 'flags':
      return 'Set flags';
    case 'end':
      return short(node.title);
    case 'battle':
      return `Fight: ${node.encounterId} (expected level ${content.encounters.get(node.encounterId)?.expectedLevel})`;
  }
}

function counts(nodes: readonly GraphNode[]): string {
  return `${nodes.length} nodes; ${nodes.filter((item) => item.node.kind === 'battle').length} fights; ${nodes.filter((item) => item.node.kind === 'branch').length} branches; ${nodes.filter((item) => item.node.kind === 'choice').length} choices`;
}

function renderGroup(graph: StoryGraph, group: StoryGroup): string {
  const groupNodes = graph.nodes.filter((item) => item.group === group.slug);
  const parts = graph.parts.filter((part) => part.group === group.slug);
  const nodeById = new Map(graph.nodes.map((item) => [item.node.id, item]));
  const partById = new Map(
    graph.parts.flatMap((part) => part.nodeIds.map((id) => [id, part] as const)),
  );
  const mermaidIds = new Map(graph.nodes.map((item, index) => [item.node.id, `n${index}`]));
  const lines = [
    GENERATED,
    '',
    `# ${group.title} story graph`,
    '',
    '[All story graphs](./README.md)',
    '',
    `Source: [${group.source}](../../src/content/story/${group.source}).`,
    '',
    counts(groupNodes),
    '',
    'Green nodes are story entry points (new game, map interactions, cross-file targets, or roots). Hexagons are fights; diamonds are flag branches. Purple placeholders exit this file; dashed placeholders continue in another part. Counts include owned story nodes only.',
    '',
    'Edges preserve authored story-node transitions, including legacy/audit explore.next links. On connected maps, live map exits clear the story cursor and do not follow explore.next. Physical map travel and conditionally available NPC/trigger interactions are not edges here; this is not the complete world travel map. Dialogue variants change presentation, not control flow.',
    '',
  ];
  for (const part of parts) {
    const owned = new Set(part.nodeIds);
    const outgoing = graph.edges.filter((edge) => owned.has(edge.from));
    const boundaries = [
      ...new Set(outgoing.filter((edge) => !owned.has(edge.to)).map((edge) => edge.to)),
    ].sort(compare);
    lines.push(
      `<a id="part-${part.number}"></a>`,
      '',
      `## Part ${part.number}: entry \`${part.entry}\``,
      '',
      `${part.nodeIds.length} owned nodes.`,
      '',
      '```mermaid',
      'flowchart TD',
    );
    for (const id of part.nodeIds) {
      const item = nodeById.get(id);
      if (item === undefined) throw new Error(`Missing node ${id}`);
      const label = `${escapeMermaidLabel(id)}<br/>${escapeMermaidLabel(title(item.node, graph.content))}`;
      const shape =
        item.node.kind === 'battle'
          ? `{{"${label}"}}`
          : item.node.kind === 'branch'
            ? `{"${label}"}`
            : item.node.kind === 'end'
              ? `(["${label}"])`
              : `["${label}"]`;
      lines.push(`  ${mermaidIds.get(id)}${shape}${item.entry ? ':::entry' : ''}`);
    }
    for (const id of boundaries) {
      const target = partById.get(id);
      if (target === undefined) throw new Error(`Missing continuation for ${id}`);
      const external = target.group !== group.slug;
      const label = escapeMermaidLabel(
        `${id} — ${external ? `exit to ${target.group}` : 'continue'} / part ${target.number}`,
      );
      lines.push(`  ${mermaidIds.get(id)}["${label}"]:::${external ? 'external' : 'continuation'}`);
    }
    for (const edge of outgoing)
      lines.push(
        `  ${mermaidIds.get(edge.from)} -->|"${escapeMermaidLabel(edge.label)}"| ${mermaidIds.get(edge.to)}`,
      );
    lines.push(
      '  classDef entry fill:#dcfce7,stroke:#15803d,color:#14532d',
      '  classDef external fill:#f3e8ff,stroke:#7e22ce,color:#581c87',
      '  classDef continuation fill:#f8fafc,stroke:#475569,color:#0f172a,stroke-dasharray:5 5',
      '```',
      '',
    );
    if (boundaries.length) {
      lines.push('Continuations:', '');
      for (const id of boundaries) {
        const target = partById.get(id);
        if (target === undefined) throw new Error(`Missing continuation for ${id}`);
        lines.push(
          `- \`${id}\` → [${target.group}, part ${target.number}](./${target.group}.md#part-${target.number})`,
        );
      }
      lines.push('');
    }
  }
  return `${lines.join('\n')}\n`;
}

/** Deterministic Markdown, formatted with the same async Prettier configuration as the repository. */
export async function generateStoryDocs(
  options: StoryGraphOptions = {},
  outputDirectory = resolve('docs/story'),
): Promise<Map<string, string>> {
  const graph = buildStoryGraph(options);
  const documents = new Map(
    graph.groups.map((group) => [`${group.slug}.md`, renderGroup(graph, group)]),
  );
  const lines = [
    GENERATED,
    '',
    '# Story graphs',
    '',
    'Generated from the effective runtime story nodes, including party voice dialogue variants. Regenerate with `npm run docs:story`; verify committed output with `npm run docs:story -- --check`.',
    '',
    counts(graph.nodes),
    '',
    'Each runtime story node is owned by exactly one diagram. Entry points are highlighted; cross-file exits and cross-part continuations link to the diagram owning their target. Files over 80 nodes split from entry points into parts of at most 80 owned nodes. Boundary placeholders are excluded from counts.',
    '',
    'Edges show every authored story transition, choice condition and flag mutation. Branches use runtime truthiness (false and 0 take the falsy route). Map NPCs and triggers mark possible entry points without inventing transitions or bypassing their conditions. Connected map exits clear the story cursor rather than following explore.next; those authored links are labeled legacy/audit exits. Physical map travel is outside this graph. Dialogue variants are presentation alternatives, not transitions.',
    '',
    '| Story file | Nodes | Fights | Branches | Choices | Parts |',
    '| --- | ---: | ---: | ---: | ---: | ---: |',
  ];
  for (const group of graph.groups) {
    const nodes = graph.nodes.filter((item) => item.group === group.slug);
    lines.push(
      `| [${group.title}](./${group.slug}.md) | ${nodes.length} | ${nodes.filter((item) => item.node.kind === 'battle').length} | ${nodes.filter((item) => item.node.kind === 'branch').length} | ${nodes.filter((item) => item.node.kind === 'choice').length} | ${graph.parts.filter((part) => part.group === group.slug).length} |`,
    );
  }
  documents.set('README.md', `${lines.join('\n')}\n`);
  const prettierOptions = (await resolveConfig(resolve(outputDirectory, 'README.md'))) ?? {};
  for (const [name, markdown] of documents)
    documents.set(
      name,
      await format(markdown, {
        ...prettierOptions,
        filepath: resolve(outputDirectory, name),
        parser: 'markdown',
      }),
    );
  return documents;
}

/** Check mode performs no writes and reports every missing or stale document. */
export async function syncStoryDocs(
  documents: ReadonlyMap<string, string>,
  outputDirectory: string,
  check: boolean,
): Promise<string[]> {
  const stale: string[] = [];
  if (!check) await mkdir(outputDirectory, { recursive: true });
  for (const [name, generated] of documents) {
    const path = resolve(outputDirectory, name);
    if (!check) {
      await writeFile(path, generated, 'utf8');
      continue;
    }
    let current: string | undefined;
    try {
      current = await readFile(path, 'utf8');
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
    if (current !== generated) stale.push(name);
  }
  return stale;
}

export async function runCli(
  args: readonly string[] = process.argv.slice(2),
  outputDirectory = resolve('docs/story'),
): Promise<number> {
  if (args.some((argument) => argument !== '--check')) {
    console.error('Usage: npm run docs:story -- [--check]');
    return 1;
  }
  const documents = await generateStoryDocs({}, outputDirectory);
  const stale = await syncStoryDocs(documents, outputDirectory, args.includes('--check'));
  if (stale.length) {
    console.error(
      `Story graphs are missing or stale: ${stale.join(', ')}. Run \`npm run docs:story\` and commit docs/story/.`,
    );
    return 1;
  }
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  runCli()
    .then((code) => {
      process.exitCode = code;
    })
    .catch((error: unknown) => {
      console.error(error);
      process.exitCode = 1;
    });
}
