"""Step 8: pack the test sheets and write their timing.

One atlas a character (public/art/units/style-test/<name>.json + lossless .webp): the four diagonals' idle (2 cels) and
walk (6 cels), 128x128 cels, frames named <key>/<clip>/<i>. src/content/assets/worldStyleTest.ts holds what the manifest
needs: cel time, start cel, the foot anchor and the walk's clip ms a tile per heading.

The clip ms a tile: a loop covers loop_tiles (stride.json, the planted foot's measured travel at one art px a world px),
so cycle / loop_tiles holds the foot. The animator divides a sheet's value by the oblique figure scale (1.25, which this
atlas's 80 px tile cancels), so the value written is that times 1.25.

usage (repo root): python3 -I art/source/style-test-world-chars/tools/pack.py"""
import json
from pathlib import Path
from PIL import Image
HERE = Path(__file__).resolve().parent.parent
REPO = HERE.parents[2]
KEYS = {'kaya': 'unit.fire.kaya', 'sura': 'unit.water.sura', 'bo': 'unit.earth.bo', 'gao': 'npc.shopkeeper'}
DIRS = {'south-east': 'SouthEast', 'south-west': 'SouthWest', 'north-east': 'NorthEast', 'north-west': 'NorthWest'}
HEADINGS = ['east', 'southEast', 'south', 'southWest', 'west', 'northWest', 'north', 'northEast']
DRAWN = {'east': 'south-east', 'southEast': 'south-east', 'south': 'south-west', 'southWest': 'south-west', 'west': 'south-west',
         'northWest': 'north-west', 'north': 'north-west', 'northEast': 'north-east'}
CEL_MS = 120        # the walk's authored cel time
START_CEL = 2       # the first passing pose, so a walk starts mid-stride from standing
IDLE_MS = [1300, 1100]
FIGURE_SCALE = 1.25
FOOT_ROW = 112


def main():
    stride = json.load(open(HERE / 'stride.json'))
    out = REPO / 'public/art/units/style-test'; out.mkdir(parents=True, exist_ok=True)
    data = {}
    for name, key in KEYS.items():
        cels = []
        for d, D in DIRS.items():
            for clip, n in (('idle', 2), ('walk', 6)):
                for i in range(n): cels.append((f'{key}/{clip}{D}/{i}', HERE / f'cels/{name}/{clip}/{d}/{i:02d}.png'))
        cols = 16; rows = (len(cels) + cols - 1) // cols
        sheet = Image.new('RGBA', (cols * 128, rows * 128), (0, 0, 0, 0)); frames = {}
        for i, (fname, p) in enumerate(cels):
            x, y = (i % cols) * 128, (i // cols) * 128
            sheet.alpha_composite(Image.open(p).convert('RGBA'), (x, y))
            frames[fname] = {'frame': {'x': x, 'y': y, 'w': 128, 'h': 128}, 'rotated': False, 'trimmed': False,
                             'spriteSourceSize': {'x': 0, 'y': 0, 'w': 128, 'h': 128}, 'sourceSize': {'w': 128, 'h': 128}}
        sheet.save(out / f'{name}.webp', lossless=True, quality=100, method=6)
        json.dump({'frames': frames, 'meta': {'app': 'four-nations-tactics', 'version': '1', 'image': f'{name}.webp', 'format': 'RGBA8888',
                                              'size': {'w': sheet.width, 'h': sheet.height}, 'scale': '1'}}, open(out / f'{name}.json', 'w'))
        ms = []
        for h in HEADINGS:
            L = stride[f'{name}/{DRAWN[h]}']['loop_tiles']
            ms.append(round(6 * CEL_MS / L * FIGURE_SCALE, 1))
        data[name] = ms
    ts = ['/**', ' * Generated by `art/source/style-test-world-chars/tools/pack.py`; do not edit by hand.', ' *',
          ' * The world-style figure test (`?style=world`): the walk\'s authored cel time and start cel, the foot anchor, and the',
          ' * clip ms a tile per heading (`HEADINGS` order) that holds the planted foot, from the measured stride (`stride.json`)',
          ' * times the oblique figure scale the animator divides by.', ' */',
          "export type WorldStyleName = 'kaya' | 'sura' | 'bo' | 'gao';", '',
          'export const WORLD_STYLE_TEST: Readonly<', '  Record<', '    WorldStyleName,', '    {',
          '      readonly walkCels: number;', '      readonly walkCelMs: number;', '      readonly walkStartCel: number;',
          '      readonly idleMs: readonly number[];', '      readonly anchorY: number;', '      readonly walkMsPerTile: readonly number[];',
          '    }', '  >', '> = {']
    for name, ms in data.items():
        ts += [f'  {name}: {{', '    walkCels: 6,', f'    walkCelMs: {CEL_MS},', f'    walkStartCel: {START_CEL},',
               f'    idleMs: [{IDLE_MS[0]}, {IDLE_MS[1]}],', f'    anchorY: {round((FOOT_ROW + 0.5) / 128, 6)},',
               f'    walkMsPerTile: [{", ".join(str(v) for v in ms)}],', '  },']
    ts += ['};', '']
    (REPO / 'src/content/assets/worldStyleTest.ts').write_text('\n'.join(ts))
    print(json.dumps(data))


if __name__ == '__main__':
    main()
